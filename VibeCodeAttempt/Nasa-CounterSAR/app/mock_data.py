"""
CounterSAR — Synthetic Data Generator
======================================
Generates clearly labelled SYNTHETIC satellite and environmental data
for development and demonstration purposes.

╔══════════════════════════════════════════════════════════════════════╗
║  ⚠️  ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC.               ║
║     It does NOT represent real satellite observations.              ║
║     Every output is tagged with is_synthetic=True.                  ║
╚══════════════════════════════════════════════════════════════════════╝

Study Area           : Kuttanad, Kerala, India
SAR Source Model     : Sentinel-1 C-band IW (simulated)
Rainfall Model       : CHIRPS-style daily rainfall (simulated)
Reanalysis Model     : ERA5-style soil moisture & temperature (simulated)
"""

import numpy as np
import pandas as pd
import xarray as xr


# ─── Constants ──────────────────────────────────────────────────────────

SYNTHETIC_LABEL = "⚠️ SYNTHETIC DATA — Not real satellite observations"

# Kuttanad study area bounding box (EPSG:4326)
KUTTANAD_BBOX = {
    "lat_min": 9.25,
    "lat_max": 9.58,
    "lon_min": 76.30,
    "lon_max": 76.55,
}

SPATIAL_RES = 0.01          # ~1.1 km per pixel
S1_REVISIT_DAYS = 12        # Sentinel-1 repeat cycle
DEFAULT_START = "2023-01-01"
DEFAULT_END = "2024-06-30"
RNG_SEED = 42


# ─── Seasonal Models ───────────────────────────────────────────────────

def _seasonal_backscatter(doy: np.ndarray) -> np.ndarray:
    """
    Seasonal VV backscatter model for Kuttanad (dB).

    Physical basis:
      - Dry season (Dec–May): exposed soil and standing vegetation
        produce relatively high backscatter (~−8 dB).
      - SW monsoon (Jun–Sep): widespread flooding lowers backscatter
        due to specular reflection off open water (~−15 dB).
      - NE monsoon (Oct–Nov): secondary moderate dip from renewed rain.
    """
    base = -8.0
    sw_dip = -7.0 * np.exp(-0.5 * ((doy - 200) / 40) ** 2)
    ne_dip = -2.5 * np.exp(-0.5 * ((doy - 290) / 20) ** 2)
    return base + sw_dip + ne_dip


def _seasonal_rainfall(doy: np.ndarray) -> np.ndarray:
    """Seasonal daily rainfall model for Kuttanad (mm/day)."""
    sw = 20.0 * np.exp(-0.5 * ((doy - 180) / 35) ** 2)
    ne = 8.0 * np.exp(-0.5 * ((doy - 300) / 25) ** 2)
    return 1.5 + sw + ne


def _seasonal_soil_moisture(doy: np.ndarray) -> np.ndarray:
    """Seasonal volumetric soil moisture model for Kuttanad (m³/m³)."""
    base = 0.25
    wet = 0.35 * np.exp(-0.5 * ((doy - 210) / 50) ** 2)
    return np.clip(base + wet, 0.15, 0.60)


# ─── Public Generators ─────────────────────────────────────────────────

def generate_sar_timeseries(
    start_date: str = DEFAULT_START,
    end_date: str = DEFAULT_END,
    seed: int = RNG_SEED,
) -> pd.DataFrame:
    """
    Generate a SYNTHETIC Sentinel-1 SAR backscatter time series.

    Returns
    -------
    pd.DataFrame
        Columns: date, vv_db, vh_db, orbit, is_synthetic, data_label
    """
    rng = np.random.default_rng(seed)
    dates = pd.date_range(start_date, end_date, freq=f"{S1_REVISIT_DAYS}D")
    doy = dates.dayofyear.values.astype(float)

    vv_db = _seasonal_backscatter(doy) + rng.normal(0, 0.8, len(dates))
    vh_db = vv_db + rng.normal(-7.0, 0.5, len(dates))
    orbits = np.where(np.arange(len(dates)) % 2 == 0, "ascending", "descending")

    return pd.DataFrame({
        "date": dates,
        "vv_db": np.round(vv_db, 2),
        "vh_db": np.round(vh_db, 2),
        "orbit": orbits,
        "is_synthetic": True,
        "data_label": SYNTHETIC_LABEL,
    })


def generate_environmental_timeseries(
    start_date: str = DEFAULT_START,
    end_date: str = DEFAULT_END,
    seed: int = RNG_SEED,
) -> pd.DataFrame:
    """
    Generate SYNTHETIC daily environmental data (rainfall, soil moisture,
    temperature) modelled after CHIRPS and ERA5 patterns for Kuttanad.

    Returns
    -------
    pd.DataFrame
        Columns: date, rainfall_mm, soil_moisture, temperature_c,
                 is_synthetic, data_label
    """
    rng = np.random.default_rng(seed + 1)
    dates = pd.date_range(start_date, end_date, freq="D")
    doy = dates.dayofyear.values.astype(float)

    # Rainfall — gamma-distributed around the seasonal mean
    rain_scale = np.maximum(_seasonal_rainfall(doy) / 2.0, 0.1)
    rainfall = np.round(np.clip(rng.gamma(2.0, rain_scale), 0, 120), 1)

    # Soil moisture
    sm = _seasonal_soil_moisture(doy) + rng.normal(0, 0.03, len(dates))
    soil_moisture = np.round(np.clip(sm, 0.10, 0.65), 3)

    # Temperature — tropical baseline with slight seasonal swing
    temp_base = 28.0
    temp_seasonal = -2.0 * np.cos(2 * np.pi * doy / 365)
    temp_monsoon = -1.5 * np.exp(-0.5 * ((doy - 200) / 50) ** 2)
    temperature = np.round(
        temp_base + temp_seasonal + temp_monsoon + rng.normal(0, 1.0, len(dates)),
        1,
    )

    return pd.DataFrame({
        "date": dates,
        "rainfall_mm": rainfall,
        "soil_moisture": soil_moisture,
        "temperature_c": temperature,
        "is_synthetic": True,
        "data_label": SYNTHETIC_LABEL,
    })


def generate_spatial_backscatter(
    target_date: str = "2023-07-15",
    seed: int = RNG_SEED,
) -> xr.Dataset:
    """
    Generate a SYNTHETIC 2-D SAR backscatter snapshot over Kuttanad.

    Returns
    -------
    xr.Dataset
        Variables: vv_db(latitude, longitude), vh_db(latitude, longitude)
    """
    rng = np.random.default_rng(seed + 2)

    lats = np.arange(KUTTANAD_BBOX["lat_min"], KUTTANAD_BBOX["lat_max"], SPATIAL_RES)
    lons = np.arange(KUTTANAD_BBOX["lon_min"], KUTTANAD_BBOX["lon_max"], SPATIAL_RES)

    doy = float(pd.Timestamp(target_date).dayofyear)
    base_vv = _seasonal_backscatter(np.array([doy]))[0]

    lat_g, lon_g = np.meshgrid(lats, lons, indexing="ij")

    # Simulated water bodies (backwaters → lower backscatter)
    water = np.sin(5 * (lat_g - 9.3)) * np.cos(8 * (lon_g - 76.35))
    water_effect = np.where(water > 0.6, -6.0, 0.0)

    # Simulated urban area near Alappuzha
    urban = 3.0 * np.exp(
        -0.5 * (((lat_g - 9.49) / 0.03) ** 2 + ((lon_g - 76.34) / 0.03) ** 2)
    )

    noise = rng.normal(0, 1.5, (len(lats), len(lons)))
    vv = base_vv + water_effect + urban + noise
    vh = vv + rng.normal(-7.0, 0.5, vv.shape)

    return xr.Dataset(
        {
            "vv_db": (["latitude", "longitude"], np.round(vv, 2)),
            "vh_db": (["latitude", "longitude"], np.round(vh, 2)),
        },
        coords={"latitude": lats, "longitude": lons},
        attrs={
            "title": "CounterSAR Synthetic SAR Backscatter",
            "data_type": "SYNTHETIC",
            "warning": SYNTHETIC_LABEL,
            "study_area": "Kuttanad, Kerala, India",
            "date": target_date,
            "crs": "EPSG:4326",
            "units": "dB",
            "simulated_source": "Sentinel-1 C-band IW mode",
            "spatial_resolution_deg": SPATIAL_RES,
        },
    )


def generate_anomaly_candidates(
    sar_df: pd.DataFrame,
    n_anomalies: int = 5,
    seed: int = RNG_SEED,
) -> pd.DataFrame:
    """
    Generate SYNTHETIC anomaly records for dashboard demonstration.

    Returns
    -------
    pd.DataFrame
        Columns: date, latitude, longitude, z_score, anomaly_type,
                 persistent, is_synthetic, data_label
    """
    rng = np.random.default_rng(seed + 3)
    n = min(n_anomalies, len(sar_df))
    idx = rng.choice(len(sar_df), size=n, replace=False)
    dates = sar_df.iloc[idx]["date"].values

    types = [
        "unexplained_drop",
        "unexplained_rise",
        "persistent_change",
        "transient_spike",
        "gradual_shift",
    ]

    rows = []
    for i, dt in enumerate(dates):
        rows.append({
            "date": pd.Timestamp(dt),
            "latitude": round(
                rng.uniform(KUTTANAD_BBOX["lat_min"], KUTTANAD_BBOX["lat_max"]), 4
            ),
            "longitude": round(
                rng.uniform(KUTTANAD_BBOX["lon_min"], KUTTANAD_BBOX["lon_max"]), 4
            ),
            "z_score": round(rng.uniform(2.5, 5.0), 2),
            "anomaly_type": types[i % len(types)],
            "persistent": bool(rng.random() > 0.4),
            "is_synthetic": True,
            "data_label": SYNTHETIC_LABEL,
        })

    return pd.DataFrame(rows)


